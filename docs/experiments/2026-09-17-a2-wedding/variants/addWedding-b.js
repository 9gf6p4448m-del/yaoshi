  /* 乙案「紙新娘紅包」（A2 S6 方案，2026-09-17）——主意象：**紅包口掀開，裡面立起一尊蓋頭紙新娘**，
     封口燒焦，一縷黑髮從紅包口垂出來，旁邊斜插一支白骨髮簪。
     剪影＝扁紅包底座 ＋ 上方直立的錐形小人（蓋頭到肩）＋ 斜出的簪子，與甲案的「橫綑十字＋垂穗」完全不同族。
     ★為什麼不是喜氣紅包★：紅包只剩「容器」的角色，真正被讀到的是從裡面站起來的人形；
     紅蓋頭下不是臉而是骨白的空臉，喜事的符號（蓋頭、紅包）全被替換成殮葬的材質（骨、髮、焦紙）。
     兩面可讀：新娘身體／頭／蓋頭是六邊環繞體（任何自轉角都有面），正面看到骨白空臉、
     背面看到紅蓋頭與垂到腰的長黑髮；底座是躺平的 xz 面，俯視相機永遠在。
     決定性：全部座標寫死，不取 R()、不碰 Math.random。 */
  const addWedding = () => {
    const red = 0xb03127, redDark = 0x5a1417, veilRed = 0xbb3730; // 底座紅包／暗面／蓋頭（同一硃紅家族，比紅布亮一階）
    const char = 0x1a1412; // 焦黑封口
    const bone = 0xdcd6c2, boneDim = 0xb8b1a0; // 骨白（只用在空臉與髮簪這兩塊小面；暗面刻意偏灰，偏褐會讀成木棍／撞王船紙舟）
    const hair = 0x120f0e; // 黑髮
    const cx = -0.045; // 新娘往左讓位給右邊的髮簪
    const hx = (r, i, y) => { const a = (i / 6) * Math.PI * 2; return [cx + Math.cos(a) * r, y, Math.sin(a) * r]; };
    const band = (y0, r0, y1, r1, color, skip) => {
      for (let i = 0; i < 6; i++) { if (i === skip) continue; b.quad(hx(r0, i, y0), hx(r0, (i + 1) % 6, y0), hx(r1, (i + 1) % 6, y1), hx(r1, i, y1), color); }
    };

    // ① 底座紅包：躺平的扁封＋被掀開的封口蓋片，封口一條燒焦
    xz(-0.200, -0.095, 0.205, 0.095, 0.026, red);
    xy(-0.200, 0.008, 0.205, 0.026, 0.095, redDark);
    xz(-0.200, 0.050, 0.205, 0.086, 0.028, char);
    b.quad([-0.155, 0.026, -0.095], [0.155, 0.026, -0.095], [0.135, 0.105, -0.145], [-0.135, 0.105, -0.145], redDark);
    b.quad([-0.135, 0.105, -0.145], [0.135, 0.105, -0.145], [0.128, 0.122, -0.152], [-0.128, 0.122, -0.152], char);

    // ② 紙新娘：裙擺→腰→肩 兩段六邊錐台（環繞體，轉到任何角度都有面）
    band(0.028, 0.088, 0.135, 0.062, red);
    band(0.135, 0.062, 0.190, 0.050, redDark);
    // ③ 頭與頭頂
    band(0.190, 0.042, 0.242, 0.040, bone);
    for (let i = 0; i < 6; i++) b.tri([cx, 0.248, 0], hx(0.040, i, 0.242), hx(0.040, (i + 1) % 6, 0.242), bone);
    // ④ 紅蓋頭：罩住頭與肩，**只留正面那一片開口**（i===1 那一格＝ +z 正面）
    band(0.288, 0.046, 0.170, 0.072, veilRed, 1);
    for (let i = 0; i < 6; i++) b.tri([cx, 0.296, 0], hx(0.046, (i + 1) % 6, 0.288), hx(0.046, i, 0.288), veilRed);

    // ⑤ 蓋頭底下的骨白空臉：兩個黑眼窩與一道黑口，沒有五官只有洞
    xy(cx - 0.030, 0.196, cx + 0.030, 0.246, 0.043, bone);
    xy(cx - 0.024, 0.222, cx - 0.008, 0.234, 0.045, hair);
    xy(cx + 0.008, 0.222, cx + 0.024, 0.234, 0.045, hair);
    xy(cx - 0.012, 0.202, cx + 0.012, 0.210, 0.045, hair);

    // ⑥ 黑髮：背面垂到腰的長髮、蓋頭兩側漏出的兩縷
    xy(cx - 0.056, 0.058, cx + 0.056, 0.200, -0.052, hair);
    xy(cx - 0.042, 0.120, cx - 0.024, 0.202, 0.046, hair);
    xy(cx + 0.024, 0.120, cx + 0.042, 0.202, 0.046, hair);
    // 從紅包口垂出來、拖到桌面的一縷（前後兩份，側轉時不消失）
    for (const z of [-0.010, 0.010]) {
      b.quad([0.058, 0.030, z], [0.082, 0.028, z], [0.150, 0.070, z], [0.126, 0.078, z], hair);
      b.quad([0.126, 0.078, z], [0.150, 0.070, z], [0.196, 0.036, z], [0.180, 0.026, z], hair);
    }

    // ⑦ 白骨髮簪：斜插在紅包口上，簪頭一顆骨節
    for (const z of [-0.012, 0.012]) {
      b.quad([0.096, 0.030, z], [0.110, 0.024, z], [0.216, 0.142, z], [0.202, 0.150, z], bone);
      b.quad([0.198, 0.138, z], [0.216, 0.128, z], [0.232, 0.160, z], [0.212, 0.168, z], boneDim);
    }

    // ⑧ 桌面上一小灘黑漬
    xz(0.020, 0.100, 0.160, 0.158, 0.004, char);
  };
