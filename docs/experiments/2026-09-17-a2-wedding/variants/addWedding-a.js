  /* 甲案「綑屍紅包」（A2 S6 方案，2026-09-17）——主意象：**被白麻繩十字捆死、封口燒焦滲黑的紅包疊**。
     剪影＝底下兩只歪疊的扁紅包 ＋ 一只幾乎直立的紅封被繩勒住 ＋ 兩條垂到桌面的麻穗。
     ★為什麼不是喜氣紅包★：喜氣紅包的語法是「平整、金印、完好」；這裡三件事同時反過來——
     封口是撕裂的焦黑（燒過的紙錢邊）、囍字被撕成兩半錯開、綁法是喪事的白麻而不是紅絲線。
     兩面可讀：立封做成「前後兩面＋四條側緣」的薄盒（不是單片），麻繩橫向繞整圈，
     轉到側面看仍是一塊有厚度的紅板被白繩勒住；底下兩只是躺平的 xz 面，俯視相機任何角度都在。
     決定性：全部座標寫死，不取 R()、不碰 Math.random。 */
  const addWedding = () => {
    const red = 0xb03127, redDark = 0x5a1417, redLit = 0xc4412f; // 硃紅／暗紅／受光面（比紅布 0x6e1616 亮一階才跳得出來）
    const char = 0x181210; // 焦黑（燒過的封口與滲出的黑舌）
    const hemp = 0xcdc3a8, hempDark = 0x8b826f; // 喪事白麻繩：只做細條，不鋪大面（避開白虎面具的米白大面）
    const ink = 0x14100e; // 撕成兩半的黑囍
    const t = 0.018, hw = 0.115, y0 = 0.020, y1 = 0.292; // 立封半厚／半寬／下緣／上緣（高 < 白虎 0.345）

    // ① 底下兩只歪疊的扁紅包：躺平的 xz 面，俯視相機在任何自轉角都讀得到
    xz(-0.225, -0.105, 0.155, 0.075, 0.012, redDark);
    xy(-0.225, 0.000, 0.155, 0.012, 0.075, char); // 前緣燒焦
    xz(-0.150, -0.060, 0.230, 0.120, 0.026, red);
    xy(-0.150, 0.014, 0.230, 0.026, 0.120, redDark);

    // ② 立起的紅封：前後兩面＋四條側緣＝有厚度的薄盒（單片會在側面消失）
    for (const z of [-t, t]) xy(-hw, y0, hw, y1, z, z < 0 ? redDark : red);
    b.quad([-hw, y1, -t], [hw, y1, -t], [hw, y1, t], [-hw, y1, t], redLit);
    b.quad([-hw, y0, t], [hw, y0, t], [hw, y0, -t], [-hw, y0, -t], redDark);
    b.quad([-hw, y0, -t], [-hw, y1, -t], [-hw, y1, t], [-hw, y0, t], redDark);
    b.quad([hw, y0, t], [hw, y1, t], [hw, y1, -t], [hw, y0, -t], redDark);

    // ③ 封口燒焦撕裂＋往下滲的三條黑舌（前後各一份）
    for (const z of [-t - 0.001, t + 0.001]) {
      xy(-hw, y1 - 0.064, hw, y1 - 0.024, z, char);
      xy(-0.082, y1 - 0.104, -0.052, y1 - 0.030, z, char);
      xy(-0.012, y1 - 0.124, 0.016, y1 - 0.030, z, char);
      xy(0.056, y1 - 0.084, 0.082, y1 - 0.030, z, char);
    }

    // ④ 撕成兩半、上下錯開的黑囍（喜字被撕開＝婚事斷了）
    for (const z of [-t - 0.002, t + 0.002]) {
      xy(-0.064, 0.152, 0.008, 0.172, z, ink);
      xy(-0.042, 0.178, -0.014, 0.214, z, ink);
      xy(0.026, 0.104, 0.080, 0.124, z, ink);
      xy(0.042, 0.068, 0.068, 0.106, z, ink);
    }

    // ⑤ 白麻繩：**兩道**橫繩各繞整圈（前後＋左右兩側）＋一條縱繩 ⇒ 讀成「捆死」而不是「綁個蝴蝶結」
    const yb = 0.128, bh = 0.011, bz = t + 0.004;
    for (const yc of [yb, 0.058]) {
      for (const z of [-bz, bz]) xy(-hw - 0.012, yc - bh, hw + 0.012, yc + bh, z, hemp);
      b.quad([-hw - 0.012, yc - bh, -bz], [-hw - 0.012, yc + bh, -bz], [-hw - 0.012, yc + bh, bz], [-hw - 0.012, yc - bh, bz], hempDark);
      b.quad([hw + 0.012, yc - bh, bz], [hw + 0.012, yc + bh, bz], [hw + 0.012, yc + bh, -bz], [hw + 0.012, yc - bh, -bz], hempDark);
    }
    for (const z of [-bz, bz]) xy(-0.012, y0, 0.012, y1, z, hemp);

    // ⑥ 繩結與兩條往外斜甩的短麻穗（垂到桌面會讀成椅腳，r1 實拍確認過）
    for (const z of [-t - 0.006, t + 0.006]) {
      xy(-0.026, yb - 0.020, 0.026, yb + 0.020, z, hemp);
      b.quad([0.024, yb - 0.006, z], [0.044, yb - 0.026, z], [0.118, 0.072, z], [0.096, 0.090, z], hempDark);
      b.quad([-0.024, yb - 0.006, z], [-0.046, yb - 0.026, z], [-0.114, 0.068, z], [-0.090, 0.086, z], hempDark);
    }

    // ⑦ 桌面上滲出來的一灘黑漬
    xz(-0.090, 0.055, 0.020, 0.135, 0.004, char);
  };
