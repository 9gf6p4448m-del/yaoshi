export const KINDS = Object.keys(EMBLEM);

const _geo = new Map();
const _out = new Map();

function pathOf(flat) {
  const pts = [];
  for (let i = 0; i < flat.length; i += 2) pts.push(new THREE.Vector2(flat[i], flat[i + 1]));
  return pts;
}

/** kind 的 ShapeGeometry（建一次、全場共用）。找不到 kind 就 throw——靜默給個預設形狀＝雙射斷言假綠。 */
export function geomOf(kind) {
  let g = _geo.get(kind);
  if (g) return g;
  const spec = EMBLEM[kind];
  if (!spec) throw new Error(`emblems: 沒有 kind="${kind}"（合法值 ${KINDS.length} 個，見 vocab.js 的 EMBLEM_OF）`);
  const outline = Array.isArray(spec) ? spec : spec.o;
  const shape = new THREE.Shape(pathOf(outline));
  if (!Array.isArray(spec) && spec.h) shape.holes.push(new THREE.Path(pathOf(spec.h)));
  g = new THREE.ShapeGeometry(shape);
  g.userData.fxShared = true; // trait-fx 的清場不得 dispose 共用 geometry
  _geo.set(kind, g);
  return g;
}

/** kind 的外框線（LineLoop 用；同樣共用） */
export function outlineOf(kind) {
  let g = _out.get(kind);
  if (g) return g;
  const spec = EMBLEM[kind];
  if (!spec) throw new Error(`emblems: 沒有 kind="${kind}"`);
  const flat = Array.isArray(spec) ? spec : spec.o;
  const pts = [];
  for (let i = 0; i < flat.length; i += 2) pts.push(new THREE.Vector3(flat[i], flat[i + 1], 0));
  g = new THREE.BufferGeometry().setFromPoints(pts);
  g.userData.fxShared = true;
  _out.set(kind, g);
  return g;
}

/** 只在頁面卸載時呼叫（共用 geometry 不隨單套演出釋放） */
export function disposeAll() {
  _geo.forEach((g) => g.dispose()); _geo.clear();
  _out.forEach((g) => g.dispose()); _out.clear();
}

/** 診斷：每個 kind 的外框頂點數與三角形數（給 tests/fxvocab.test.mjs 驗 ≤24／≤22） */
export function stats() {
  return KINDS.map((k) => {
    const spec = EMBLEM[k];
    const outline = Array.isArray(spec) ? spec : spec.o;
    const hole = Array.isArray(spec) ? 0 : (spec.h ? spec.h.length / 2 : 0);
    const g = geomOf(k);
    return { kind: k, verts: outline.length / 2, hole, tris: g.index ? g.index.count / 3 : g.attributes.position.count / 3 };
  });
}
