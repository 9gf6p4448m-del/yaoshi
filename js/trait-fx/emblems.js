import * as THREE from 'three';

const TAU = Math.PI * 2;
/** n 芒星：外徑 rOut、內徑 rIn，共 2n 個頂點 */
function star(n, rOut, rIn, rot = 0) {
  const p = [];
  for (let i = 0; i < n * 2; i++) { const a = rot + (i / (n * 2)) * TAU; const r = i % 2 ? rIn : rOut; p.push(+(Math.cos(a) * r).toFixed(3), +(Math.sin(a) * r).toFixed(3)); }
  return p;
}
/** 半徑逐點不同的多邊形（給「芒不得等分等長」的殘日用，ART_BIBLE §9） */
function jag(radii, rot = 0) {
  const p = [];
  radii.forEach((r, i) => { const a = rot + (i / radii.length) * TAU; p.push(+(Math.cos(a) * r).toFixed(3), +(Math.sin(a) * r).toFixed(3)); });
  return p;
}
/** 正多邊形 */
function poly(n, r, rot = 0) { return jag(new Array(n).fill(r), rot); }

